"""D70: no V1, deprecated or migration path is left. A leftover key is reported, never migrated.

The report line is ``⚠ unknown key `<dotted.key>` in <absolute path> → delete it``. It appears in
``carter check --host`` (every hit), in ``carter install`` and ``carter update`` (once per key, at
the end) and in ``carter check`` (workspace files). It never fails a command and changes nothing.
"""

from __future__ import annotations

import importlib
import json
import os
import re
from pathlib import Path

import pytest
import yaml
from click.testing import CliRunner

from carter import unknownkeys
from carter.cli import main
from carter.identity.config import ConfigError, load_identity

EMAIL = "12345+llm-bot@users.noreply.github.com"
LINE = "⚠ unknown key `{key}` in {path} → delete it"


@pytest.fixture
def home() -> Path:
    return Path(os.environ["HOME"])


@pytest.fixture
def cfg_path(home: Path) -> Path:
    path = home / ".carter" / "config.toml"
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def line(key: str, path: Path) -> str:
    return LINE.format(key=key, path=path)


class TestGone:
    @pytest.mark.parametrize("module", ["carter.identity.migrate"])
    def test_the_modules_are_gone(self, module: str) -> None:
        with pytest.raises(ModuleNotFoundError):
            importlib.import_module(module)

    def test_no_migration_state_or_shim_names_remain(self) -> None:
        from carter import config, plans
        from carter.guard import permissions, state
        from carter.identity import schema

        assert not hasattr(schema.IdentityConfig, "needs_migration")
        assert not hasattr(config, "V1_AGENT_KEYS") and not hasattr(config, "identity_warnings")
        assert not hasattr(plans, "DEPRECATED_PUSH_POLICY_KEY")
        assert "warnings" not in plans.PlanValidation().__dict__
        assert "form" not in state.PERMISSION_FIELDS and not hasattr(permissions, "_form")

    def test_install_has_no_bot_name_option(self) -> None:
        params = {p.name for p in main.commands["install"].params}
        assert "bot_name" not in params

    def test_the_old_hash_sets_are_gone(self) -> None:
        from carter.install import components

        assert not hasattr(components, "_KNOWN_PREVIOUS_AGENTS_MD_SHA256")
        assert not hasattr(components, "_write_upgrade_note")

    def test_no_user_doc_has_a_migration_or_upgrade_note_section(self) -> None:
        root = Path(__file__).resolve().parents[1]
        for rel in ("docs/guides/install.md", "docs/reference/cli.md", "docs/troubleshooting.md",
                    "docs/reference/files-and-paths.md", "docs/reference/configuration.md",
                    "docs/guides/write-operations.md"):  # fmt: skip
            text = (root / rel).read_text()
            for gone in ("schema1.bak", "upgrade-notes", "schema-1", "schema 1", "--bot-name"):
                assert gone not in text, (rel, gone)


class TestSchemaIsAlwaysTwo:
    def test_a_missing_schema_key_is_read_as_2(self, cfg_path: Path) -> None:
        cfg_path.write_text(f'[identity]\nlogin = "llm-bot"\nid = 12345\nemail = "{EMAIL}"\n')
        cfg = load_identity(cfg_path)
        assert (cfg.state, cfg.schema, cfg.identity.login) == ("current", 2, "llm-bot")

    def test_an_explicit_schema_1_is_an_unsupported_value(self, cfg_path: Path) -> None:
        cfg_path.write_text("schema = 1\n")
        with pytest.raises(ConfigError) as err:
            load_identity(cfg_path)
        assert "unsupported schema" in err.value.detail

    def test_old_keys_are_listed_not_interpreted(self, cfg_path: Path) -> None:
        cfg_path.write_text(
            '[attribution]\nname = "bot"\nemail = "x@y.z"\nfooter = "mine"\n'
            '[git]\nsigning_key = "k"\n[identity]\nbot_name = "b"\n'
        )
        cfg = load_identity(cfg_path)
        assert cfg.attribution.footer == "mine"
        assert cfg.identity.login == ""  # nothing is read from the old attribution block
        assert set(cfg.unknown_keys) == {
            "attribution.name", "attribution.email", "git.signing_key", "identity.bot_name",
        }  # fmt: skip

    def test_the_old_default_footer_is_just_a_footer(self, cfg_path: Path) -> None:
        cfg_path.write_text('[attribution]\nfooter = "This comment was generated by carter-bot."\n')
        assert load_identity(cfg_path).attribution.footer.endswith("carter-bot.")


class TestInstallOps:
    def test_a_missing_file_is_created_with_schema_2(self, fake_opencode, base_dir: Path) -> None:
        fake_opencode("opencode v2.1.4")
        res = CliRunner().invoke(main, ["install", "--base-dir", str(base_dir)])
        assert res.exit_code == 0, res.output
        assert "schema = 2" in (base_dir / "carter" / "config.toml").read_text()

    def test_an_old_file_is_left_alone_and_nothing_is_backed_up(
        self, fake_opencode, base_dir: Path
    ) -> None:
        fake_opencode("opencode v2.1.4")
        cfg = base_dir / "carter" / "config.toml"
        cfg.parent.mkdir(parents=True)
        original = '[attribution]\nname = "bot"\nfooter = "mine"\n'
        cfg.write_text(original)
        res = CliRunner().invoke(main, ["install", "--base-dir", str(base_dir)])
        assert res.exit_code == 0, res.output
        assert cfg.read_text() == original
        assert not list(cfg.parent.glob("*.bak"))
        assert line("attribution.name", cfg) in res.output

    def test_a_modified_agents_md_is_user_modified_and_leaves_no_note(
        self, fake_opencode, base_dir: Path
    ) -> None:
        fake_opencode("opencode v2.1.4")
        agents_md = base_dir / "opencode" / "AGENTS.md"
        agents_md.parent.mkdir(parents=True)
        agents_md.write_text("# my own global rules\n")
        res = CliRunner().invoke(main, ["install", "--base-dir", str(base_dir)])
        assert res.exit_code == 0, res.output
        assert agents_md.read_text() == "# my own global rules\n"
        assert "user-modified" in res.output
        assert not (base_dir / "carter" / "upgrade-notes").exists()

    def test_the_recorded_hash_still_upgrades_an_unmodified_earlier_text_in_place(
        self, fake_opencode, base_dir: Path
    ) -> None:
        """The real host's AGENTS.md is the pre-D68 text: the manifest knows its hash."""
        from carter.install import components
        from carter.install.ownership import sha256_bytes

        fake_opencode("opencode v2.1.4")
        assert CliRunner().invoke(main, ["install", "--base-dir", str(base_dir)]).exit_code == 0
        agents_md = base_dir / "opencode" / "AGENTS.md"
        earlier = components._OPENCODE_AGENTS_MD.replace("gh pr create", "gh pr open")
        agents_md.write_text(earlier)
        manifest_file = base_dir / "carter" / "manifest.json"
        manifest = json.loads(manifest_file.read_text())
        manifest["file_hashes"][str(agents_md)] = sha256_bytes(earlier.encode())
        manifest_file.write_text(json.dumps(manifest))

        res = CliRunner().invoke(main, ["install", "--base-dir", str(base_dir)])

        assert res.exit_code == 0, res.output
        assert agents_md.read_text() == components._OPENCODE_AGENTS_MD

    def test_an_unrecorded_earlier_text_is_user_modified(
        self, fake_opencode, base_dir: Path
    ) -> None:
        from carter.install import components

        fake_opencode("opencode v2.1.4")
        agents_md = base_dir / "opencode" / "AGENTS.md"
        agents_md.parent.mkdir(parents=True)
        earlier = components._OPENCODE_AGENTS_MD.replace("gh pr create", "gh pr open")
        agents_md.write_text(earlier)  # no manifest knows it
        res = CliRunner().invoke(main, ["install", "--base-dir", str(base_dir)])
        assert agents_md.read_text() == earlier and "user-modified" in res.output


class TestPlans:
    PLAN = (
        "---\nid: 001-demo\nstatus: active\ncreated: 2026-01-01\nupdated: 2026-01-02\n"
        "push_policy: manual\nmust_haves:\n  truths: [a]\n  artifacts: []\n  key_links: []\n"
        "---\n# P\n"
    )

    def test_push_policy_is_neither_an_error_nor_a_warning_of_validation(
        self, tmp_path: Path
    ) -> None:
        from carter.plans import validate_plans_dir

        plan = tmp_path / "active" / "001-demo"
        plan.mkdir(parents=True)
        (plan / "README.md").write_text(self.PLAN)
        assert validate_plans_dir(tmp_path).errors == []


def workspace(tmp_path: Path, *, plan: bool = False, yaml_keys: dict | None = None) -> Path:
    ws = tmp_path / "ws"
    ws.mkdir()
    assert CliRunner().invoke(main, ["init", str(ws), "--no-git-state"]).exit_code == 0
    path = ws / ".carter" / "carter.yaml"
    data = yaml.safe_load(path.read_text())
    if yaml_keys:
        data["identity"] = yaml_keys
        path.write_text(yaml.dump(data))
    if plan:
        directory = ws / ".carter" / "state" / "plans" / "active" / "001-demo"
        directory.mkdir(parents=True)
        (directory / "README.md").write_text(TestPlans.PLAN)
    return ws


class TestReport:
    def test_the_line_has_the_exact_format(self, tmp_path: Path) -> None:
        hit = unknownkeys.Hit("attribution.name", tmp_path / "config.toml")
        assert hit.line() == line("attribution.name", tmp_path / "config.toml")
        assert (
            hit.line(unicode=False)
            == f"! unknown key `attribution.name` in {tmp_path}/config.toml -> delete it"
        )

    def test_config_toml_keys(self, cfg_path: Path) -> None:
        cfg_path.write_text(
            'schema = 2\n[attribution]\nname = "bot"\n[identity]\nbot_name = "b"\nlogin = "x"\n'
        )
        keys = {h.key for h in unknownkeys.config_toml(cfg_path)}
        assert keys == {"attribution.name", "identity.bot_name"}

    def test_an_unreadable_or_absent_file_reports_nothing(self, cfg_path: Path) -> None:
        assert unknownkeys.config_toml(cfg_path) == []  # absent
        cfg_path.write_text("this is = = not toml")
        assert unknownkeys.config_toml(cfg_path) == []

    def test_carter_yaml_retired_identity_keys(self, tmp_path: Path) -> None:
        ws = workspace(tmp_path, yaml_keys={"git_account": "me", "bot_name": "b", "role": "author"})
        hits = unknownkeys.carter_yaml(ws / ".carter" / "carter.yaml")
        assert {h.key for h in hits} == {"identity.git_account", "identity.bot_name"}

    def test_plan_front_matter_push_policy(self, tmp_path: Path) -> None:
        ws = workspace(tmp_path, plan=True)
        (hit,) = unknownkeys.workspace(ws)
        assert hit.key == "push_policy"
        assert hit.path == ws / ".carter/state/plans/active/001-demo/README.md"

    def test_v1_permission_tuples_in_guard_state(self, home: Path) -> None:
        cfg = home / ".config" / "opencode" / "opencode.jsonc"
        cfg.parent.mkdir(parents=True)
        cfg.write_text(json.dumps({"agent": {"build": {"permission": {"carter_push": "deny"}}}}))
        state = home / ".carter" / "guard-state.json"
        state.parent.mkdir(parents=True, exist_ok=True)
        state.write_text(
            json.dumps(
                {
                    "schema": 1,
                    "opencode_config": str(cfg),
                    "agent_permissions": [
                        {"agent": "build", "key": "permission.carter_push", "value": "deny",
                         "preexisting": False, "form": "v1"},
                        {"agent": "plan", "key": "permission.carter_push", "value": "deny",
                         "preexisting": False, "form": "v2"},
                    ],
                }
            )
        )  # fmt: skip
        (hit,) = unknownkeys.v1_permissions(None)
        assert (hit.key, hit.path) == ("agent.build.permission", cfg)

    def test_a_v1_tuple_whose_entry_is_gone_reports_nothing(self, home: Path) -> None:
        cfg = home / ".config" / "opencode" / "opencode.jsonc"
        cfg.parent.mkdir(parents=True)
        cfg.write_text("{}")
        state = home / ".carter" / "guard-state.json"
        state.parent.mkdir(parents=True, exist_ok=True)
        state.write_text(
            json.dumps({"schema": 1, "opencode_config": str(cfg), "agent_permissions": [
                {"agent": "build", "key": "permission.carter_push", "value": "deny",
                 "preexisting": False, "form": "v1"}]})
        )  # fmt: skip
        assert unknownkeys.v1_permissions(None) == []

    def test_old_mcp_entries(self, home: Path) -> None:
        cfg = home / ".config" / "opencode" / "opencode.json"
        cfg.parent.mkdir(parents=True)
        cfg.write_text(
            json.dumps({"mcp": {"carter-github": {"type": "local"}, "mine": {}, "servers": {}}})
        )
        assert [h.key for h in unknownkeys.old_mcp_entries(None)] == ["mcp.carter-github"]

    def test_once_per_key_keeps_the_first_path(self, tmp_path: Path) -> None:
        a = unknownkeys.Hit("push_policy", tmp_path / "a")
        b = unknownkeys.Hit("push_policy", tmp_path / "b")
        c = unknownkeys.Hit("identity.bot_name", tmp_path / "c")
        assert unknownkeys.once_per_key([a, b, c]) == [a, c]


class TestCommands:
    def test_check_host_lists_every_hit_and_does_not_fail_on_them(
        self, cfg_path: Path, tmp_path: Path
    ) -> None:
        cfg_path.write_text('[attribution]\nname = "bot"\nemail = "e"\n')
        res = CliRunner().invoke(main, ["check", "--host", str(tmp_path)])
        for key in ("attribution.name", "attribution.email"):
            assert line(key, cfg_path) in res.output
        assert "unknown key" not in "".join(
            ln for ln in res.output.splitlines() if "problem" in ln and "✗" in ln
        )

    def test_check_host_exit_code_ignores_unknown_keys(
        self, cfg_path: Path, tmp_path: Path
    ) -> None:
        clean = CliRunner().invoke(main, ["check", "--host", str(tmp_path)])
        cfg_path.write_text('[attribution]\nname = "bot"\n')
        dirty = CliRunner().invoke(main, ["check", "--host", str(tmp_path)])
        assert dirty.exit_code == clean.exit_code

    def test_check_workspace_reports_yaml_and_plan_keys(self, tmp_path: Path) -> None:
        ws = workspace(tmp_path, plan=True, yaml_keys={"bot_name": "b"})
        res = CliRunner().invoke(main, ["check", str(ws), "--no-harness"])
        assert res.exit_code == 0, res.output
        assert line("identity.bot_name", ws / ".carter" / "carter.yaml") in res.output
        assert (
            line("push_policy", ws / ".carter/state/plans/active/001-demo/README.md") in res.output
        )
        assert "Workspace OK" in res.output

    def test_update_reports_each_key_once_at_the_end(self, cfg_path: Path, tmp_path: Path) -> None:
        ws = workspace(tmp_path, plan=True)
        second = ws / ".carter/state/plans/active/002-more"
        second.mkdir()
        (second / "README.md").write_text(TestPlans.PLAN.replace("001-demo", "002-more"))
        cfg_path.write_text('[attribution]\nname = "bot"\n')
        res = CliRunner().invoke(main, ["update", str(ws)])
        assert res.exit_code == 0, res.output
        assert res.output.count("unknown key `push_policy`") == 1
        assert line("attribution.name", cfg_path) in res.output
        assert res.output.rstrip().splitlines()[-1].startswith("⚠ unknown key")

    def test_install_reports_at_the_end(self, fake_opencode, base_dir: Path) -> None:
        fake_opencode("opencode v2.1.4")
        cfg = base_dir / "carter" / "config.toml"
        cfg.parent.mkdir(parents=True)
        cfg.write_text('[identity]\nbot_name = "b"\n')
        res = CliRunner().invoke(main, ["install", "--base-dir", str(base_dir)])
        assert res.exit_code == 0, res.output
        lines = [ln for ln in res.output.splitlines() if ln.strip()]
        assert lines[-1] == line("identity.bot_name", cfg)

    def test_nothing_is_changed_by_the_report(self, cfg_path: Path, tmp_path: Path) -> None:
        text = '[attribution]\nname = "bot"\n[git]\nsigning_key = "k"\n'
        cfg_path.write_text(text)
        CliRunner().invoke(main, ["check", "--host", str(tmp_path)])
        assert cfg_path.read_text() == text

    def test_the_report_never_prints_a_value(self, cfg_path: Path, tmp_path: Path) -> None:
        cfg_path.write_text('[attribution]\nname = "SECRET-VALUE-123"\n')
        res = CliRunner().invoke(main, ["check", "--host", "-v", str(tmp_path)])
        assert "SECRET-VALUE-123" not in res.output


def test_the_writer_names_unknown_keys_and_still_refuses_to_lose_them(cfg_path: Path) -> None:
    from carter.identity.schema import IdentityConfig
    from carter.identity.writer import UnmodelledKeysError, write_config

    cfg_path.write_text('[attribution]\nname = "bot"\n')
    with pytest.raises(UnmodelledKeysError, match=r"unknown key\(s\) `attribution.name`"):
        write_config(IdentityConfig(state="current"), cfg_path)
    assert re.search(r'name = "bot"', cfg_path.read_text())
