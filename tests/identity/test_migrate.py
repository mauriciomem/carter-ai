class TestMigrationIsExplicit:
    def test_ops_config_load_never_writes(self, cfg_path):
        from carter.ops.config import Config

        cfg_path.write_text(INSTALLED_V1)
        before = snapshot(cfg_path)
        Config.load(cfg_path)
        assert snapshot(cfg_path) == before
        assert [p.name for p in cfg_path.parent.iterdir()] == ["config.toml"]

    def test_readers_do_not_migrate(self, cfg_path):
        from carter.identity import load_footer

        cfg_path.write_text(INSTALLED_V1)
        before = snapshot(cfg_path)
        assert load_identity(cfg_path).needs_migration
        load_footer(cfg_path)
        assert snapshot(cfg_path) == before

    def test_only_the_installer_imports_the_migration(self):
        allowed = {"carter/install/components.py", "carter/identity/migrate.py"}
        importers = set()
        for src in (REPO / "carter").rglob("*.py"):
            for node in ast.walk(ast.parse(src.read_text(encoding="utf-8"))):
                mods = []
                if isinstance(node, ast.ImportFrom) and node.module:
                    mods = [node.module, *(f"{node.module}.{a.name}" for a in node.names)]
                elif isinstance(node, ast.Import):
                    mods = [a.name for a in node.names]
                if "carter.identity.migrate" in mods:
                    importers.add(str(src.relative_to(REPO)))
        assert importers <= allowed, importers - allowed

    def test_migrate_module_stays_small(self):
        lines = (REPO / "carter" / "identity" / "migrate.py").read_text().splitlines()
        assert len(lines) <= 220
