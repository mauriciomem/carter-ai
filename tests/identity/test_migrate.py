def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def snapshot(path: Path) -> tuple[str, int]:
    return sha(path), path.stat().st_mtime_ns


@pytest.fixture
def cfg_path(tmp_path: Path) -> Path:
    return tmp_path / "config.toml"


class TestMapping:
    def test_valid_noreply_email_migrates_with_login_id_and_name(self):
        cfg, warnings = map_schema1({"attribution": {"name": "llm-bot", "email": EMAIL}})
        assert cfg.identity == Identity(login="llm-bot", id=12345, name="llm-bot", email=EMAIL)
        assert warnings == ()

    def test_email_login_wins_over_a_different_name(self):
        cfg, _ = map_schema1({"attribution": {"name": "Display Name", "email": EMAIL}})
        assert (cfg.identity.login, cfg.identity.name) == ("llm-bot", "Display Name")

    def test_the_carter_bot_default_is_dropped_and_is_t0(self):
        doc = {
            "attribution": {"name": "carter-bot", "email": "carter-bot@users.noreply.github.com"}
        }
        cfg, warnings = map_schema1(doc)
        assert cfg.identity == Identity()
        assert any("email" in w and "T0" in w for w in warnings)
        assert resolve(cfg, workspace=None, env={}).tier == "t0"

    @pytest.mark.parametrize("email", ["bot@acme.test", "llm-bot@users.noreply.github.com", ""])
    def test_other_emails_are_dropped_with_a_warning(self, email):
        cfg, warnings = map_schema1({"attribution": {"name": "acme-bot", "email": email}})
        assert cfg.identity == Identity()  # name only moves together with a valid email
        if email:
            assert any("email" in w for w in warnings)

    def test_name_alone_is_not_migrated(self):
        cfg, _ = map_schema1({"attribution": {"name": "acme-bot"}})
        assert cfg.identity.name == ""

    def test_non_string_values_are_dropped_with_a_warning(self):
        cfg, warnings = map_schema1({"attribution": {"email": 5, "footer": 7}})
        assert cfg.identity == Identity()
        assert cfg.attribution == Attribution()
        assert len(warnings) == 2

    @pytest.mark.parametrize(
        "footer",
        ["This comment was generated by acme-bot.", '_quotes " and \\ and ñ 🚀_', " spaced ", "x"],
    )
    def test_footer_is_kept_exactly(self, footer):
        cfg, _ = map_schema1({"attribution": {"footer": footer}})
        assert cfg.attribution.footer == footer

    def test_missing_footer_gets_the_default(self):
        cfg, _ = map_schema1({"attribution": {"name": "x"}})
        assert cfg.attribution == Attribution()

    def test_git_signing_key_is_dropped_and_the_warning_names_it(self):
        cfg, warnings = map_schema1({"git": {"signing_key": HUMAN_KEY}})
        assert cfg.signing == Signing()
        text = " ".join(warnings)
        assert "[git] signing_key" in text
        assert HUMAN_KEY not in text and "id_ed25519" not in text  # never echo the path

    def test_empty_signing_key_is_dropped_silently(self):
        _, warnings = map_schema1({"git": {"signing_key": ""}})
        assert warnings == ()

    def test_unknown_schema1_keys_are_reported(self):
        _, warnings = map_schema1({"attribution": {"extra": "x"}, "jira": {"url": "u"}})
        text = " ".join(warnings)
        assert "attribution.extra" in text and "jira" in text and "backup" in text

    def test_defaults_elsewhere_and_no_workspaces_invented(self):
        cfg, _ = map_schema1({"attribution": {"name": "llm-bot", "email": EMAIL}})
        assert cfg.signing == Signing()
        assert cfg.disclosure == Disclosure()
        assert cfg.workspaces == {}
        assert cfg.state == "current" and cfg.schema == 2

    def test_explicit_schema_1_key_is_accepted(self):
        cfg, warnings = map_schema1({"schema": 1, "attribution": {"footer": "f"}})
        assert cfg.attribution.footer == "f" and warnings == ()


class TestMigrateFile:
    def test_migrates_an_installed_file(self, cfg_path):
        cfg_path.write_text(INSTALLED_V1)

        result = migrate_config(cfg_path)

        assert result.status == "migrated"
        loaded = load_identity(cfg_path)
        assert loaded.state == "current"
        assert loaded.attribution.footer == DEFAULT_FOOTER  # the old default is "unset" (D68 i)
        assert loaded.identity == Identity()  # carter-bot default email -> T0
        text = cfg_path.read_text()
        assert "schema = 2" in text
        assert "carter-bot@" not in text and "signing_key" not in text
        assert HUMAN_KEY not in text and "id_ed25519" not in text
        assert any("signing_key" in w for w in result.warnings)

    def test_t1_identity_survives(self, cfg_path):
        cfg_path.write_text(T1_V1)
        migrate_config(cfg_path)
        r = resolve(load_identity(cfg_path), workspace=None, env={})
        assert r.tier == "t1"
        assert load_identity(cfg_path).attribution.footer == "Generated by the team bot."

    def test_backup_holds_the_exact_original_with_mode_0600(self, cfg_path):
        cfg_path.write_text(INSTALLED_V1)
        migrate_config(cfg_path)
        bak = cfg_path.with_name(BACKUP_NAME)
        assert BACKUP_NAME == "config.toml.schema1.bak"
        assert bak.read_text() == INSTALLED_V1
        assert stat.S_IMODE(bak.stat().st_mode) == 0o600
        assert stat.S_IMODE(cfg_path.stat().st_mode) == 0o600

    def test_second_run_is_a_no_op(self, cfg_path):
        cfg_path.write_text(INSTALLED_V1)
        migrate_config(cfg_path)
        before, bak_before = snapshot(cfg_path), snapshot(cfg_path.with_name(BACKUP_NAME))

        again = migrate_config(cfg_path)

        assert again.status == "current"
        assert snapshot(cfg_path) == before
        assert snapshot(cfg_path.with_name(BACKUP_NAME)) == bak_before
        assert sorted(p.name for p in cfg_path.parent.iterdir()) == sorted(
            [BACKUP_NAME, "config.toml"]
        )

    def test_missing_file_is_absent_and_nothing_is_created(self, cfg_path):
        assert migrate_config(cfg_path).status == "absent"
        assert list(cfg_path.parent.iterdir()) == []

    def test_schema2_is_never_remigrated(self, cfg_path):
        ensure_config(cfg_path)
        before = snapshot(cfg_path)
        assert migrate_config(cfg_path).status == "current"
        assert snapshot(cfg_path) == before

    @pytest.mark.parametrize("schema", ["3", "99"])
    def test_future_schema_refuses_and_writes_nothing(self, cfg_path, schema):
        cfg_path.write_text(f"schema = {schema}\n")
        with pytest.raises(ConfigError) as exc:
            migrate_config(cfg_path)
        assert exc.value.code == E_CONFIG
        assert cfg_path.read_text() == f"schema = {schema}\n"
        assert [p.name for p in cfg_path.parent.iterdir()] == ["config.toml"]

    def test_unparseable_toml_refuses_loudly_and_changes_nothing(self, cfg_path):
        bad = '[attribution]\nname = "unterminated\n'
        cfg_path.write_text(bad)
        with pytest.raises(ConfigError) as exc:
            migrate_config(cfg_path)
        assert exc.value.code == E_CONFIG
        assert cfg_path.read_text() == bad
        assert [p.name for p in cfg_path.parent.iterdir()] == ["config.toml"]
        with pytest.raises(ConfigError):  # identity stays fail-closed
            load_identity(cfg_path)

    def test_unknown_future_keys_in_a_schema2_file_are_left_alone(self, cfg_path):
        text = "schema = 2\n[extra]\nprecious = 1\n"
        cfg_path.write_text(text)
        assert migrate_config(cfg_path).status == "current"
        assert cfg_path.read_text() == text


class TestFailureSafety:
    def test_failed_replace_leaves_the_original_intact(self, cfg_path, monkeypatch):
        cfg_path.write_text(INSTALLED_V1)
        monkeypatch.setattr(os, "replace", lambda *a, **k: (_ for _ in ()).throw(OSError("boom")))

        with pytest.raises(OSError, match="boom"):
            migrate_config(cfg_path)

        assert cfg_path.read_text() == INSTALLED_V1
        assert cfg_path.with_name(BACKUP_NAME).read_text() == INSTALLED_V1  # written first
        assert sorted(p.name for p in cfg_path.parent.iterdir()) == sorted(
            [BACKUP_NAME, "config.toml"]
        )

    def test_retry_after_a_failure_succeeds_with_one_backup(self, cfg_path, monkeypatch):
        cfg_path.write_text(INSTALLED_V1)
        with monkeypatch.context() as m:
            m.setattr(os, "replace", lambda *a, **k: (_ for _ in ()).throw(OSError("boom")))
            with pytest.raises(OSError):
                migrate_config(cfg_path)

        assert migrate_config(cfg_path).status == "migrated"
        assert cfg_path.with_name(BACKUP_NAME).read_text() == INSTALLED_V1
        assert load_identity(cfg_path).state == "current"

    def test_a_backup_of_a_different_file_is_never_overwritten_nor_ignored(self, cfg_path):
        # A stale backup must not silently stand in for the current original.
        cfg_path.write_text(INSTALLED_V1)
        bak = cfg_path.with_name(BACKUP_NAME)
        bak.write_text("OLDER ORIGINAL")

        with pytest.raises(MigrationError, match=BACKUP_NAME):
            migrate_config(cfg_path)

        assert bak.read_text() == "OLDER ORIGINAL"
        assert cfg_path.read_text() == INSTALLED_V1

    def test_an_identical_existing_backup_is_fine(self, cfg_path):
        cfg_path.write_text(INSTALLED_V1)
        cfg_path.with_name(BACKUP_NAME).write_text(INSTALLED_V1)
        assert migrate_config(cfg_path).status == "migrated"

    def test_write_error_in_the_backup_leaves_the_original(self, cfg_path, monkeypatch):
        cfg_path.write_text(INSTALLED_V1)
        real_open = os.open

        def deny(path, flags, *a, **k):
            if str(path).endswith(BACKUP_NAME):
                raise PermissionError("no backup for you")
            return real_open(path, flags, *a, **k)

        monkeypatch.setattr(os, "open", deny)
        with pytest.raises(PermissionError):
            migrate_config(cfg_path)
        assert cfg_path.read_text() == INSTALLED_V1


