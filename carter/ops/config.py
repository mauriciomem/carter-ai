"""Carter-ops configuration loader.

Loads settings from ~/.carter/config.toml (non-secrets) and environment
variables (secrets). Validates required settings per operation domain.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path


def _home() -> Path:
    return Path.home()


def _default_config_path() -> Path:
    return _home() / ".carter" / "config.toml"


def _parse_toml(text: str) -> dict[str, dict[str, str]]:
    """Minimal TOML parser — handles [section] + key = "value" pairs only."""
    result: dict[str, dict[str, str]] = {}
    current_section = ""
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^\[(\w+)\]$", line)
        if m:
            current_section = m.group(1)
            result.setdefault(current_section, {})
            continue
        m = re.match(r'^(\w+)\s*=\s*"(.*)"$', line)
        if m:
            result.setdefault(current_section, {})[m.group(1)] = m.group(2)
    return result


@dataclass
class Config:
    # Attribution
    bot_name: str = "carter-bot"
    bot_email: str = "carter-bot@users.noreply.github.com"
    footer: str = "_This comment was generated by carter-bot._"

    # Git
    signing_key: str = ""

    # Jira
    jira_url: str = ""
    jira_email: str = ""
    jira_token: str = ""

    # GitHub
    github_token: str = ""
    github_owner: str = ""
    github_repo: str = ""

    @classmethod
    def load(cls, config_path: Path | None = None) -> Config:
        cfg = cls()

        # Load from TOML file
        path = config_path or _default_config_path()
        if path.exists():
            try:
                data = _parse_toml(path.read_text())
            except Exception:
                data = {}

            attr = data.get("attribution", {})
            cfg.bot_name = attr.get("name", cfg.bot_name)
            cfg.bot_email = attr.get("email", cfg.bot_email)
            cfg.footer = attr.get("footer", cfg.footer)

            git = data.get("git", {})
            signing_key = git.get("signing_key", "")
            if signing_key:
                cfg.signing_key = str(Path(signing_key).expanduser())

            jira = data.get("jira", {})
            cfg.jira_url = jira.get("url", "")
            cfg.jira_email = jira.get("email", "")

        # Env vars override file values (secrets always from env)
        cfg.jira_token = os.environ.get("JIRA_TOKEN", "") or os.environ.get(
            "ATLASSIAN_API_TOKEN", ""
        )
        cfg.jira_url = os.environ.get("ATLASSIAN_URL", "") or cfg.jira_url
        cfg.jira_email = os.environ.get("ATLASSIAN_EMAIL", "") or cfg.jira_email

        # GitHub
        cfg.github_token = os.environ.get("GITHUB_TOKEN", "")
        cfg.github_owner = os.environ.get("GITHUB_OWNER", "") or cfg.github_owner
        cfg.github_repo = os.environ.get("GITHUB_REPO", "") or cfg.github_repo

        # Auto-detect signing key from git config if not set
        if not cfg.signing_key:
            cfg.signing_key = _detect_signing_key()

        return cfg

    def validate_jira(self) -> list[str]:
        errors = []
        if not self.jira_url:
            errors.append("ATLASSIAN_URL not set")
        if not self.jira_email:
            errors.append("ATLASSIAN_EMAIL not set")
        if not self.jira_token:
            errors.append("JIRA_TOKEN or ATLASSIAN_API_TOKEN not set")
        return errors

    def validate_github(self) -> list[str]:
        errors = []
        if not self.github_token:
            errors.append("GITHUB_TOKEN not set")
        return errors


def _detect_signing_key() -> str:
    """Try to get signing key from git config."""
    import subprocess

    try:
        result = subprocess.run(
            ["git", "config", "user.signingkey"],
            capture_output=True,
            text=True,
            timeout=5,
        )
        if result.returncode == 0 and result.stdout.strip():
            key = result.stdout.strip()
            expanded = str(Path(key).expanduser())
            return expanded
    except (subprocess.SubprocessError, FileNotFoundError):
        pass

    # Fallback: check common key locations
    for name in ("id_ed25519", "id_rsa"):
        p = _home() / ".ssh" / name
        if p.exists():
            return str(p)

    return ""


DEFAULT_CONFIG_TOML = """\
[attribution]
name = "carter-bot"
email = "carter-bot@users.noreply.github.com"
footer = "This comment was generated by carter-bot."

[git]
signing_key = "{signing_key}"

[jira]
url = "{jira_url}"
email = "{jira_email}"
# token comes from JIRA_TOKEN or ATLASSIAN_API_TOKEN env var — never in config file
"""


def generate_default_config(signing_key: str = "", jira_url: str = "", jira_email: str = "") -> str:
    return DEFAULT_CONFIG_TOML.format(
        signing_key=signing_key,
        jira_url=jira_url,
        jira_email=jira_email,
    )
