"""Carter-ops configuration loader.

Loads settings from ~/.carter/config.toml (non-secrets) and environment
variables (secrets) for ``carter ops config --emit``.
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

from carter.home import carter_home


def _default_config_path() -> Path:
    return carter_home() / "config.toml"


def _parse_toml(text: str) -> dict[str, dict[str, str]]:
    """Minimal TOML parser — handles [section] + key = "value" pairs only."""
    result: dict[str, dict[str, str]] = {}
    current_section = ""
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^\[(\w+)\]$", line)
        if m:
            current_section = m.group(1)
            result.setdefault(current_section, {})
            continue
        m = re.match(r'^(\w+)\s*=\s*"(.*)"$', line)
        if m:
            result.setdefault(current_section, {})[m.group(1)] = m.group(2)
    return result


@dataclass
class Config:
    # Attribution
    bot_name: str = "carter-bot"
    bot_email: str = "carter-bot@users.noreply.github.com"
    footer: str = "_This comment was generated by carter-bot._"

    # Git
    signing_key: str = ""

    # GitHub
    github_token: str = ""

    @classmethod
    def load(cls, config_path: Path | None = None) -> Config:
        cfg = cls()

        # Load from TOML file
        data = read_config_toml(config_path or _default_config_path())
        if data:
            attr = data.get("attribution", {})
            cfg.bot_name = attr.get("name", cfg.bot_name)
            cfg.bot_email = attr.get("email", cfg.bot_email)
            cfg.footer = attr.get("footer", cfg.footer)

            git = data.get("git", {})
            signing_key = git.get("signing_key", "")
            if signing_key:
                cfg.signing_key = str(Path(signing_key).expanduser())

        # Secrets always come from env
        # GitHub
        cfg.github_token = os.environ.get("GITHUB_TOKEN", "")

        # Auto-detect signing key from git config if not set
        if not cfg.signing_key:
            cfg.signing_key = _detect_signing_key()

        return cfg


def git_signing_key() -> str:
    """Return ``git config user.signingkey`` verbatim, or ``""`` if unset/unavailable."""
    try:
        result = subprocess.run(
            ["git", "config", "user.signingkey"],
            capture_output=True,
            text=True,
            timeout=5,
        )
    except (subprocess.SubprocessError, FileNotFoundError):
        return ""
    if result.returncode == 0:
        return result.stdout.strip()
    return ""


def read_config_toml(path: Path) -> dict[str, dict[str, str]]:
    """Parse ``config.toml`` at ``path``; missing or unreadable files yield ``{}``."""
    if not path.exists():
        return {}
    try:
        return _parse_toml(path.read_text())
    except Exception:
        return {}


def _detect_signing_key() -> str:
    """Try to get signing key from git config, then common SSH key locations."""
    key = git_signing_key()
    if key:
        return str(Path(key).expanduser())

    for name in ("id_ed25519", "id_rsa"):
        p = Path.home() / ".ssh" / name
        if p.exists():
            return str(p)

    return ""
